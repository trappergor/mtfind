/**
 * @file file_splitter.hpp
 * @brief Разбиение файла на байтовые диапазоны, выровненные по строкам.
 *
 * Диапазон — полуинтервал [start, end) в байтах. Каждый диапазон начинается
 * либо с позиции 0, либо сразу после символа '\n', и заканчивается либо в
 * конце файла, либо на позиции начала следующей строки. Так каждый диапазон
 * содержит только целые строки, и вхождения не разрываются между потоками.
 */

#pragma once

#include <cstddef>
#include <string>
#include <vector>

namespace mtfind {

/**
 * @brief Полуинтервал [start, end) в байтах файла.
 */
struct Range {
    std::size_t start = 0; ///< Начало (включительно).
    std::size_t end = 0;   ///< Конец (не включительно).
};

/**
 * @brief Разбивает файл на @p num_parts диапазонов, выровненных по строкам.
 *
 * Алгоритм:
 *  1. Определяем размер файла.
 *  2. Режем его на @p num_parts примерно равных байтовых кусков.
 *  3. Для каждой внутренней границы ищем ближайший '\n' вправо и
 *     сдвигаем границу за него.
 *  4. Соседние диапазоны стыкуются: конец предыдущего равен началу следующего.
 *
 * Если файл пуст, возвращается пустой вектор. Если в файле меньше строк,
 * чем @p num_parts, часть диапазонов получится нулевой длины.
 *
 * @param path Путь к файлу.
 * @param num_parts Желаемое число диапазонов (>= 1).
 * @return Вектор диапазонов в порядке возрастания позиций.
 * @throw std::runtime_error если файл не открывается или num_parts == 0.
 */
std::vector<Range> split_file(const std::string& path, std::size_t num_parts);

} // namespace mtfind