/**
 * @file mask.hpp
 * @brief Компиляция маски поиска в набор литеральных сегментов.
 *
 * Маска — строка, в которой символ '?' обозначает любой одиночный символ.
 * Между символами '?' находятся литеральные сегменты — подстроки, которые
 * обязаны совпасть с текстом посимвольно.
 *
 * Компиляция один раз на весь поиск даёт:
 *  - набор сегментов для быстрой проверки кандидатов;
 *  - выбранный "якорь" — самый длинный сегмент, по которому идёт
 *    предварительный поиск алгоритмом Boyer–Moore–Horspool.
 */

#pragma once

#include <cstddef>
#include <string>
#include <vector>

namespace mtfind {

/// Значение "нет якоря" (используется, когда маска состоит только из '?').
inline constexpr std::size_t no_anchor = static_cast<std::size_t>(-1);

/**
 * @brief Литеральный сегмент маски.
 *
 * Сегменты не пересекаются и идут в порядке возрастания @ref offset.
 */
struct Segment {
    std::size_t offset = 0; ///< Смещение сегмента внутри маски.
    std::string text;       ///< Текст сегмента (без '?').
};

/**
 * @brief Скомпилированное представление маски.
 */
struct CompiledMask {
    std::string mask;              ///< Исходная маска.
    std::size_t length = 0;        ///< Длина маски в символах.
    std::vector<Segment> segments; ///< Литеральные сегменты в порядке маски.
    std::size_t anchor_index = no_anchor; ///< Индекс якоря в segments или no_anchor.
};

/**
 * @brief Компилирует маску: разбивает её на сегменты и выбирает якорь.
 *
 * Если в маске нет '?', сегмент будет один и покроет всю маску.
 * Если маска состоит только из '?', список сегментов пуст.
 *
 * @param mask Маска поиска.
 * @return Скомпилированное представление.
 * @throw std::invalid_argument если маска пуста.
 */
CompiledMask compile_mask(const std::string& mask);

} // namespace mtfind